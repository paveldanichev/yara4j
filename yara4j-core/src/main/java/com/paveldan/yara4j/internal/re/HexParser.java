package com.paveldan.yara4j.internal.re;

import com.paveldan.yara4j.ErrorCode;

/**
 * Parser for hex strings like { 01 02 ?? [2-4] (03 | 04) }. Hand-written equivalent of
 * libyara's hex_lexer.l and hex_grammar.y.
 */
public final class HexParser {

  private static final int T_EOF = -1;
  private static final int T_BYTE = 256;
  private static final int T_MASKED_BYTE = 257;
  private static final int T_NOT_BYTE = 258;
  private static final int T_MASKED_NOT_BYTE = 259;
  private static final int T_NUMBER = 260;

  private static final class Abort extends RuntimeException {
    private static final long serialVersionUID = 1L;

    Abort() {
      super(null, null, false, false);
    }
  }

  private final byte[] s;
  private final int len;
  private int pos;
  private boolean inRange;
  private int insideOr;
  private final ReAst ast = new ReAst();
  private final RegexParser.Result result = new RegexParser.Result();

  private int tok;
  private long tokValue;

  private HexParser(byte[] hex) {
    int n = 0;
    while (n < hex.length && hex[n] != 0) {
      n++;
    }
    this.s = hex;
    this.len = n;
  }

  public static RegexParser.Result parse(byte[] hex) {
    HexParser p = new HexParser(hex);
    p.ast.flags |= Re.FLAGS_FAST_REGEXP;
    p.ast.flags |= Re.FLAGS_DOT_ALL;
    try {
      p.next();
      p.expect('{');
      ReNode root = p.tokens();
      p.expect('}');
      if (p.tok != T_EOF) {
        p.syntaxError();
      }
      p.ast.root = root;
      p.result.ast = p.ast;
    } catch (Abort e) {
      p.result.ast = null;
    }
    return p.result;
  }

  private void error(String message) {
    if (result.error == ErrorCode.SUCCESS) {
      result.error = ErrorCode.INVALID_HEX_STRING;
      result.message = message;
    }
    throw new Abort();
  }

  /**
   * libyara's regexp and hex grammars are generated by Bison 3.8 without verbose errors, so
   * syntax errors don't mention the unexpected token.
   */
  private void syntaxError() {
    error("syntax error");
  }


  private void expect(int t) {
    if (tok != t) {
      syntaxError();
    }
    next();
  }

  // ---------------------------------------------------------------------------------------------
  // Lexer

  private int peek(int off) {
    int p = pos + off;
    return p < len ? s[p] & 0xFF : -1;
  }

  private static boolean isHex(int c) {
    return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
  }

  private static int hexVal(int c) {
    if (c <= '9') {
      return c - '0';
    }
    return (c | 0x20) - 'a' + 10;
  }

  private void next() {
    while (true) {
      if (pos >= len) {
        tok = T_EOF;
        return;
      }
      int c = s[pos] & 0xFF;
      if (inRange) {
        if (c == '-') {
          pos++;
          tok = '-';
          return;
        }
        if (c >= '0' && c <= '9') {
          int start = pos;
          while (pos < len && s[pos] >= '0' && s[pos] <= '9') {
            pos++;
          }
          long v = 0;
          for (int i = start; i < pos; i++) {
            int d = s[i] - '0';
            if (v > (Long.MAX_VALUE - d) / 10) {
              v = Long.MAX_VALUE;
              break;
            }
            v = v * 10 + d;
          }
          if (v > Integer.MAX_VALUE) {
            error("jump length too large");
          }
          tok = T_NUMBER;
          tokValue = v;
          return;
        }
        if (c == ']') {
          pos++;
          inRange = false;
          tok = ']';
          return;
        }
        if (c == ' ' || c == '\t' || c == '\r' || c == '\n') {
          pos++;
          continue;
        }
        error("invalid character in hex string jump");
      }
      int c1 = peek(1);
      if (isHex(c)) {
        if (isHex(c1)) {
          pos += 2;
          tok = T_BYTE;
          tokValue = hexVal(c) << 4 | hexVal(c1);
          return;
        }
        if (c1 == '?') {
          pos += 2;
          tok = T_MASKED_BYTE;
          tokValue = (hexVal(c) << 4) | 0xF000;
          return;
        }
        error("uneven number of digits in hex string");
      }
      if (c == '~') {
        int c2 = peek(2);
        if (isHex(c1) && isHex(c2)) {
          pos += 3;
          tok = T_NOT_BYTE;
          tokValue = hexVal(c1) << 4 | hexVal(c2);
          return;
        }
        if (isHex(c1) && c2 == '?') {
          pos += 3;
          tok = T_MASKED_NOT_BYTE;
          tokValue = (hexVal(c1) << 4) | 0xF000;
          return;
        }
        if (c1 == '?' && isHex(c2)) {
          pos += 3;
          tok = T_MASKED_NOT_BYTE;
          tokValue = hexVal(c2) | 0x0F00;
          return;
        }
        error("invalid not operator (~) in hex string");
      }
      if (c == '?') {
        if (isHex(c1)) {
          pos += 2;
          tok = T_MASKED_BYTE;
          tokValue = hexVal(c1) | 0x0F00;
          return;
        }
        if (c1 == '?') {
          pos += 2;
          tok = T_MASKED_BYTE;
          tokValue = 0;
          return;
        }
        error("invalid character in hex string");
      }
      if (c == '[') {
        pos++;
        inRange = true;
        tok = '[';
        return;
      }
      if (c == '/' && c1 == '*') {
        pos += 2;
        while (pos < len && !(s[pos] == '*' && pos + 1 < len && s[pos + 1] == '/')) {
          pos++;
        }
        if (pos < len) {
          pos += 2;
        }
        continue;
      }
      if (c == '/' && c1 == '/') {
        while (pos < len && s[pos] != '\n') {
          pos++;
        }
        continue;
      }
      if (c == ' ' || c == '\t' || c == '\r' || c == '\n') {
        pos++;
        continue;
      }
      if (c == '{' || c == '}' || c == '(' || c == ')' || c == '|') {
        pos++;
        tok = c;
        return;
      }
      error("invalid character in hex string");
    }
  }

  // ---------------------------------------------------------------------------------------------
  // Parser

  private boolean startsToken() {
    return tok == T_BYTE
        || tok == T_MASKED_BYTE
        || tok == T_NOT_BYTE
        || tok == T_MASKED_NOT_BYTE
        || tok == '(';
  }

  /** tokens : token | token token | token token_sequence token */
  private ReNode tokens() {
    ReNode first = token();
    if (!startsToken() && tok != '[') {
      return first;
    }
    ReNode concat = new ReNode(ReNode.CONCAT);
    concat.appendChild(first);
    boolean lastWasRange = false;
    while (startsToken() || tok == '[') {
      if (tok == '[') {
        ReNode r = range();
        r.greedy = false;
        concat.appendChild(r);
        lastWasRange = true;
      } else {
        concat.appendChild(token());
        lastWasRange = false;
      }
    }
    if (lastWasRange) {
      // The sequence can't end with a jump.
      syntaxError();
    }
    return concat;
  }

  private ReNode token() {
    if (tok == '(') {
      // insideOr is the nesting of groups.
      if (insideOr == Re.MAX_GROUP_NESTING) {
        error("groups nested too deeply");
      }
      next();
      insideOr++;
      ReNode n = alternatives();
      if (tok != ')') {
        syntaxError();
      }
      next();
      insideOr--;
      return n;
    }
    return byteNode();
  }

  private ReNode alternatives() {
    ReNode left = tokens();
    while (tok == '|') {
      next();
      markAsNotFast();
      ReNode right = tokens();
      ReNode alt = new ReNode(ReNode.ALT);
      alt.appendChild(left);
      alt.appendChild(right);
      left = alt;
    }
    return left;
  }

  private void markAsNotFast() {
    ast.flags &= ~Re.FLAGS_FAST_REGEXP;
  }

  private ReNode byteNode() {
    ReNode n;
    int v = (int) tokValue;
    switch (tok) {
      case T_BYTE:
        n = new ReNode(ReNode.LITERAL);
        n.value = v;
        n.mask = 0xFF;
        break;
      case T_NOT_BYTE:
        n = new ReNode(ReNode.NOT_LITERAL);
        n.value = v;
        n.mask = 0xFF;
        break;
      case T_MASKED_BYTE:
        {
          int mask = (v >> 8) & 0xFF;
          if (mask == 0) {
            n = new ReNode(ReNode.ANY);
            n.value = 0;
            n.mask = 0;
          } else {
            n = new ReNode(ReNode.MASKED_LITERAL);
            n.value = v & 0xFF;
            n.mask = mask;
          }
          break;
        }
      case T_MASKED_NOT_BYTE:
        n = new ReNode(ReNode.MASKED_NOT_LITERAL);
        n.value = v & 0xFF;
        n.mask = (v >> 8) & 0xFF;
        break;
      default:
        syntaxError();
        return null;
    }
    next();
    return n;
  }

  private ReNode range() {
    // current token is '['
    next();
    ReNode n;
    if (tok == T_NUMBER) {
      long a = tokValue;
      next();
      if (tok == ']') {
        next();
        if (a <= 0) {
          error("invalid jump length");
        }
        if (insideOr > 0 && a > Re.STRING_CHAINING_THRESHOLD) {
          error("jumps over " + Re.STRING_CHAINING_THRESHOLD + " not allowed inside alternation (|)");
        }
        if (a == 1) {
          n = new ReNode(ReNode.MASKED_LITERAL);
          n.value = 0;
          n.mask = 0;
        } else {
          n = new ReNode(ReNode.RANGE_ANY);
          n.value = (int) a;
          n.mask = (int) a;
        }
        return n;
      }
      if (tok != '-') {
        syntaxError();
      }
      next();
      if (tok == T_NUMBER) {
        long b = tokValue;
        next();
        if (tok != ']') {
          syntaxError();
        }
        next();
        if (insideOr > 0
            && (a > Re.STRING_CHAINING_THRESHOLD || b > Re.STRING_CHAINING_THRESHOLD)) {
          error("jumps over " + Re.STRING_CHAINING_THRESHOLD + " not allowed inside alternation (|)");
        }
        if (a < 0 || b < 0) {
          error("invalid negative jump length");
        }
        if (a > b) {
          error("invalid jump range");
        }
        n = new ReNode(ReNode.RANGE_ANY);
        n.value = (int) a;
        n.mask = (int) b;
        return n;
      }
      if (tok != ']') {
        syntaxError();
      }
      next();
      if (insideOr > 0) {
        error("unbounded jumps not allowed inside alternation (|)");
      }
      n = new ReNode(ReNode.RANGE_ANY);
      n.value = (int) a;
      n.mask = Integer.MAX_VALUE;
      return n;
    }
    if (tok == '-') {
      next();
      if (tok != ']') {
        syntaxError();
      }
      next();
      if (insideOr > 0) {
        error("unbounded jumps not allowed inside alternation (|)");
      }
      n = new ReNode(ReNode.RANGE_ANY);
      n.value = 0;
      n.mask = Integer.MAX_VALUE;
      return n;
    }
    syntaxError();
    return null;
  }
}

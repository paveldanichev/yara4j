package com.paveldan.yara4j.internal.re;

import com.paveldan.yara4j.ErrorCode;

/**
 * Parser for YARA regular expressions. This is a hand-written equivalent of libyara's
 * re_lexer.l and re_grammar.y, producing the same abstract syntax trees and accepting the same
 * syntax.
 */
public final class RegexParser {

  /** Result of parsing a regexp or hex string. */
  public static final class Result {
    /** SUCCESS, UNKNOWN_ESCAPE_SEQUENCE (a warning, ast is valid) or an error. */
    public ErrorCode error = ErrorCode.SUCCESS;

    public String message = "";
    public ReAst ast;
  }

  private static final byte[] WORD_CHARS = {
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, (byte) 0xFF, 0x03,
    (byte) 0xFE, (byte) 0xFF, (byte) 0xFF, (byte) 0x87, (byte) 0xFE, (byte) 0xFF, (byte) 0xFF,
        0x07,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
  };

  private static final byte[] SPACE_CHARS = {
    0x00, 0x3E, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
  };

  // Token types. Single character tokens use their character value.
  private static final int T_EOF = -1;
  private static final int T_CHAR = 256;
  private static final int T_RANGE = 257;
  private static final int T_CLASS = 258;
  private static final int T_WORD_CHAR = 259;
  private static final int T_NON_WORD_CHAR = 260;
  private static final int T_SPACE = 261;
  private static final int T_NON_SPACE = 262;
  private static final int T_DIGIT = 263;
  private static final int T_NON_DIGIT = 264;
  private static final int T_WORD_BOUNDARY = 265;
  private static final int T_NON_WORD_BOUNDARY = 266;

  private static final int VALID_ESCAPE_SEQUENCE = 1;
  private static final int UNKNOWN_ESCAPE_SEQUENCE = 2;

  /** Thrown to abort parsing once an error has been recorded. */
  private static final class Abort extends RuntimeException {
    private static final long serialVersionUID = 1L;

    Abort() {
      super(null, null, false, false);
    }
  }

  private final byte[] s;
  private final int len;
  private final boolean strictEscape;
  private int pos;
  private int groupDepth;
  private final ReAst ast = new ReAst();
  private final Result result = new Result();

  // current token
  private int tok;
  private int tokValue;
  private int tokRangeLo;
  private int tokRangeHi;
  private ReClass tokClass;

  private RegexParser(byte[] re, boolean strictEscape) {
    int n = 0;
    while (n < re.length && re[n] != 0) {
      n++;
    }
    this.s = re;
    this.len = n;
    this.strictEscape = strictEscape;
  }

  /** Parses a regular expression. */
  public static Result parse(byte[] re, boolean strictEscape) {
    RegexParser p = new RegexParser(re, strictEscape);
    try {
      p.next();
      ReNode root = p.alternative();
      if (p.tok != T_EOF) {
        p.syntaxError();
      }
      p.ast.root = root;
      p.result.ast = p.ast;
    } catch (Abort e) {
      p.result.ast = null;
    }
    return p.result;
  }

  // ---------------------------------------------------------------------------------------------
  // Error handling, same semantics as re_lexer.l's yyerror and yywarning.

  private void error(String message) {
    if (result.error == ErrorCode.SUCCESS || result.error == ErrorCode.UNKNOWN_ESCAPE_SEQUENCE) {
      result.error = ErrorCode.INVALID_REGULAR_EXPRESSION;
      result.message = message;
    }
    throw new Abort();
  }

  private void warning(String message) {
    if (result.error == ErrorCode.SUCCESS) {
      result.error = ErrorCode.UNKNOWN_ESCAPE_SEQUENCE;
      result.message = message;
    }
  }

  /**
   * libyara's regexp and hex grammars are generated by Bison 3.8 without verbose errors, so
   * syntax errors don't mention the unexpected token.
   */
  private void syntaxError() {
    error("syntax error");
  }


  // ---------------------------------------------------------------------------------------------
  // Lexer

  private int peek(int off) {
    int p = pos + off;
    return p < len ? s[p] & 0xFF : -1;
  }

  private static boolean isDigit(int c) {
    return c >= '0' && c <= '9';
  }

  private static boolean isHex(int c) {
    return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
  }

  private static int hexVal(int c) {
    if (c <= '9') {
      return c - '0';
    }
    return (c | 0x20) - 'a' + 10;
  }

  /** strtoll on a digit run, clamped to Long.MAX_VALUE. */
  private static long parseDigits(byte[] s, int from, int to) {
    long v = 0;
    for (int i = from; i < to; i++) {
      int d = s[i] - '0';
      if (v > (Long.MAX_VALUE - d) / 10) {
        return Long.MAX_VALUE;
      }
      v = v * 10 + d;
    }
    return v;
  }

  /**
   * Tries to match a repeat interval at the current position ("{n,m}", "{n}", etc). Returns the
   * length of the match or 0.
   */
  private int matchRange() {
    // \{{digit}*[ ]*,[ ]*{digit}*\}
    int p = pos + 1;
    int d1s = p;
    while (p < len && isDigit(s[p])) {
      p++;
    }
    int d1e = p;
    int q = p;
    while (q < len && s[q] == ' ') {
      q++;
    }
    if (q < len && s[q] == ',') {
      q++;
      while (q < len && s[q] == ' ') {
        q++;
      }
      int d2s = q;
      while (q < len && isDigit(s[q])) {
        q++;
      }
      int d2e = q;
      if (q < len && s[q] == '}') {
        long lo = parseDigits(s, d1s, d1e);
        long hi;
        if (d2s == d2e) {
          hi = Re.MAX_RANGE;
        } else {
          hi = parseDigits(s, d2s, d2e);
        }
        if (hi > Re.MAX_RANGE) {
          error("repeat interval too large");
        }
        if (hi < lo) {
          error("bad repeat interval");
        }
        tokRangeLo = (int) lo;
        tokRangeHi = (int) hi;
        return q + 1 - pos;
      }
    }
    // \{{digit}+\}
    if (d1e > d1s && p < len && s[p] == '}') {
      long v = parseDigits(s, d1s, d1e);
      if (v > Re.MAX_RANGE) {
        error("repeat interval too large");
      }
      tokRangeLo = (int) v;
      tokRangeHi = (int) v;
      return p + 1 - pos;
    }
    return 0;
  }

  /**
   * Equivalent of escaped_char_value. text is the escape sequence starting at the backslash.
   * Returns 0 if invalid, VALID_ESCAPE_SEQUENCE or UNKNOWN_ESCAPE_SEQUENCE. The value is stored
   * in escValue.
   */
  private int escValue;

  private int escapedCharValue(int c1, int c2, int c3) {
    switch (c1) {
      case 'x':
        if (!isHex(c2) || !isHex(c3)) {
          return 0;
        }
        escValue = hexVal(c2) << 4 | hexVal(c3);
        break;
      case 'n':
        escValue = '\n';
        break;
      case 't':
        escValue = '\t';
        break;
      case 'r':
        escValue = '\r';
        break;
      case 'f':
        escValue = '\f';
        break;
      case 'a':
        escValue = 7;
        break;
      case '\\':
      case '^':
      case '$':
      case '.':
      case '|':
      case '(':
      case ')':
      case '[':
      case ']':
      case '*':
      case '+':
      case '?':
      case '"':
      case '\'':
      case '-':
      case '{':
      case '}':
      case '#':
      case ':':
      case '_':
      case '=':
      case '/':
      case '!':
      case ',':
      case '@':
      case '<':
      case '>':
      case '~':
      case '&':
      case '%':
        escValue = c1;
        break;
      default:
        escValue = c1 & 0xFF;
        if (strictEscape) {
          return UNKNOWN_ESCAPE_SEQUENCE;
        }
        return VALID_ESCAPE_SEQUENCE;
    }
    return VALID_ESCAPE_SEQUENCE;
  }

  /**
   * Equivalent of read_escaped_char: reads the characters following a backslash already
   * consumed. The character after the backslash is at pos.
   */
  private int readEscapedChar() {
    int c1 = peek(0);
    if (c1 <= 0) {
      return 0;
    }
    pos++;
    int c2 = 0;
    int c3 = 0;
    if (c1 == 'x') {
      c2 = peek(0);
      if (c2 <= 0) {
        return 0;
      }
      pos++;
      c3 = peek(0);
      if (c3 <= 0) {
        return 0;
      }
      pos++;
    }
    return escapedCharValue(c1, c2, c3);
  }

  private void next() {
    if (pos >= len) {
      tok = T_EOF;
      return;
    }
    int c = s[pos] & 0xFF;
    switch (c) {
      case '{':
        {
          int m = matchRange();
          if (m > 0) {
            pos += m;
            tok = T_RANGE;
            return;
          }
          pos++;
          tok = T_CHAR;
          tokValue = c;
          return;
        }
      case '[':
        lexClass();
        return;
      case '\\':
        {
          int c1 = peek(1);
          if (isDigit(c1)) {
            error("backreferences are not allowed");
          }
          switch (c1) {
            case 'w':
              pos += 2;
              tok = T_WORD_CHAR;
              return;
            case 'W':
              pos += 2;
              tok = T_NON_WORD_CHAR;
              return;
            case 's':
              pos += 2;
              tok = T_SPACE;
              return;
            case 'S':
              pos += 2;
              tok = T_NON_SPACE;
              return;
            case 'd':
              pos += 2;
              tok = T_DIGIT;
              return;
            case 'D':
              pos += 2;
              tok = T_NON_DIGIT;
              return;
            case 'b':
              pos += 2;
              tok = T_WORD_BOUNDARY;
              return;
            case 'B':
              pos += 2;
              tok = T_NON_WORD_BOUNDARY;
              return;
            default:
              break;
          }
          pos++;
          int rc = readEscapedChar();
          if (rc == VALID_ESCAPE_SEQUENCE) {
            tok = T_CHAR;
            tokValue = escValue;
          } else if (rc == UNKNOWN_ESCAPE_SEQUENCE) {
            warning("unknown escape sequence");
            tok = T_CHAR;
            tokValue = escValue;
          } else {
            error("illegal escape sequence");
          }
          return;
        }
      case '(':
      case ')':
      case '|':
      case '$':
      case '.':
      case '^':
      case '+':
      case '*':
      case '?':
        pos++;
        tok = c;
        return;
      default:
        pos++;
        tok = T_CHAR;
        tokValue = c;
    }
  }

  private void lexClass() {
    ReClass cls = new ReClass();
    if (peek(1) == '^') {
      cls.negated = true;
      if (peek(2) == ']') {
        cls.set(']');
        pos += 3;
      } else {
        pos += 2;
      }
    } else if (peek(1) == ']') {
      cls.set(']');
      pos += 2;
    } else {
      pos += 1;
    }
    while (true) {
      if (pos >= len) {
        error("missing terminating ] for character class");
      }
      int c = s[pos] & 0xFF;
      if (c == ']') {
        pos++;
        tok = T_CLASS;
        tokClass = cls;
        return;
      }
      // Range: (\\x{hex_digit}{2}|\\.|[^]\\])-[^]]
      int startLen = 0;
      if (c == '\\') {
        int c1 = peek(1);
        if (c1 == 'x' && isHex(peek(2)) && isHex(peek(3)) && peek(4) == '-'
            && peek(5) >= 0 && peek(5) != ']') {
          startLen = 4;
        } else if (c1 >= 0 && c1 != '\n' && peek(2) == '-' && peek(3) >= 0 && peek(3) != ']') {
          startLen = 2;
        }
      } else if (peek(1) == '-' && peek(2) >= 0 && peek(2) != ']') {
        startLen = 1;
      }
      if (startLen > 0) {
        int start = c;
        int end = peek(startLen + 1);
        if (start == '\\') {
          int rc = escapedCharValue(peek(1), peek(2), peek(3));
          if (rc == 0) {
            error("illegal escape sequence");
          }
          start = escValue;
        }
        pos += startLen + 2;
        if (end == '\\') {
          if (readEscapedChar() == 0) {
            error("illegal escape sequence");
          }
          end = escValue;
        }
        if (end < start) {
          error("bad character range");
        }
        for (int x = start; x <= end; x++) {
          cls.set(x);
        }
        continue;
      }
      if (c == '\\') {
        int c1 = peek(1);
        switch (c1) {
          case 'w':
            for (int i = 0; i < 32; i++) {
              cls.bitmap[i] |= WORD_CHARS[i];
            }
            pos += 2;
            continue;
          case 'W':
            for (int i = 0; i < 32; i++) {
              cls.bitmap[i] |= (byte) ~WORD_CHARS[i];
            }
            pos += 2;
            continue;
          case 's':
            for (int i = 0; i < 32; i++) {
              cls.bitmap[i] |= SPACE_CHARS[i];
            }
            pos += 2;
            continue;
          case 'S':
            for (int i = 0; i < 32; i++) {
              cls.bitmap[i] |= (byte) ~SPACE_CHARS[i];
            }
            pos += 2;
            continue;
          case 'd':
            for (int x = '0'; x <= '9'; x++) {
              cls.set(x);
            }
            pos += 2;
            continue;
          case 'D':
            for (int i = 0; i < 32; i++) {
              if (i == 6) {
                continue;
              }
              if (i == 7) {
                cls.bitmap[i] |= (byte) 0xFC;
              } else {
                cls.bitmap[i] = (byte) 0xFF;
              }
            }
            pos += 2;
            continue;
          default:
            break;
        }
        pos++;
        int rc = readEscapedChar();
        if (rc == VALID_ESCAPE_SEQUENCE) {
          cls.set(escValue);
        } else if (rc == UNKNOWN_ESCAPE_SEQUENCE) {
          warning("unknown escape sequence");
          cls.set(escValue);
        } else {
          error("illegal escape sequence");
        }
        continue;
      }
      if (c >= 32 && c < 127) {
        cls.set(c);
        pos++;
      } else if (c == '\n') {
        // Not matched by any rule in flex's char_class state, flex echoes it and skips it.
        pos++;
      } else {
        error("non-ascii character");
      }
    }
  }

  // ---------------------------------------------------------------------------------------------
  // Parser

  private void markAsNotFast() {
    ast.flags &= ~Re.FLAGS_FAST_REGEXP;
  }

  private ReNode alternative() {
    ReNode left = concatenation();
    while (tok == '|') {
      next();
      markAsNotFast();
      ReNode right;
      if (tok == '|' || tok == ')' || tok == T_EOF) {
        right = new ReNode(ReNode.EMPTY);
      } else {
        right = concatenation();
      }
      ReNode alt = new ReNode(ReNode.ALT);
      alt.appendChild(left);
      alt.appendChild(right);
      left = alt;
    }
    return left;
  }

  private boolean startsRepeat() {
    switch (tok) {
      case '(':
      case '.':
      case T_CHAR:
      case T_WORD_CHAR:
      case T_NON_WORD_CHAR:
      case T_SPACE:
      case T_NON_SPACE:
      case T_DIGIT:
      case T_NON_DIGIT:
      case T_CLASS:
      case T_WORD_BOUNDARY:
      case T_NON_WORD_BOUNDARY:
      case '^':
      case '$':
        return true;
      default:
        return false;
    }
  }

  private ReNode concatenation() {
    if (!startsRepeat()) {
      syntaxError();
    }
    ReNode concat = new ReNode(ReNode.CONCAT);
    concat.appendChild(repeat());
    while (startsRepeat()) {
      concat.appendChild(repeat());
    }
    return concat;
  }

  private ReNode repeat() {
    switch (tok) {
      case T_WORD_BOUNDARY:
        next();
        return new ReNode(ReNode.WORD_BOUNDARY);
      case T_NON_WORD_BOUNDARY:
        next();
        return new ReNode(ReNode.NON_WORD_BOUNDARY);
      case '^':
        next();
        return new ReNode(ReNode.ANCHOR_START);
      case '$':
        next();
        return new ReNode(ReNode.ANCHOR_END);
      default:
        break;
    }
    ReNode single = single();
    ReNode n;
    switch (tok) {
      case '*':
      case '+':
        {
          int type = tok == '*' ? ReNode.STAR : ReNode.PLUS;
          next();
          markAsNotFast();
          n = new ReNode(type);
          n.appendChild(single);
          if (tok == '?') {
            next();
            ast.flags |= Re.FLAGS_UNGREEDY;
            n.greedy = false;
          } else {
            ast.flags |= Re.FLAGS_GREEDY;
          }
          return n;
        }
      case '?':
      case T_RANGE:
        {
          int start;
          int end;
          if (tok == '?') {
            start = 0;
            end = 1;
          } else {
            start = tokRangeLo;
            end = tokRangeHi;
          }
          next();
          boolean greedy = true;
          if (tok == '?') {
            next();
            greedy = false;
            ast.flags |= Re.FLAGS_UNGREEDY;
          } else {
            ast.flags |= Re.FLAGS_GREEDY;
          }
          if (single.type == ReNode.ANY) {
            n = new ReNode(ReNode.RANGE_ANY);
          } else {
            markAsNotFast();
            n = new ReNode(ReNode.RANGE);
            n.appendChild(single);
          }
          n.value = start;
          n.mask = end;
          n.greedy = greedy;
          return n;
        }
      default:
        return single;
    }
  }

  private ReNode single() {
    ReNode n;
    switch (tok) {
      case '(':
        if (groupDepth == Re.MAX_GROUP_NESTING) {
          error("groups nested too deeply");
        }
        next();
        groupDepth++;
        n = alternative();
        groupDepth--;
        if (tok != ')') {
          syntaxError();
        }
        next();
        return n;
      case '.':
        next();
        n = new ReNode(ReNode.ANY);
        n.value = 0;
        n.mask = 0;
        return n;
      case T_CHAR:
        n = new ReNode(ReNode.LITERAL);
        n.value = tokValue;
        n.mask = 0xFF;
        next();
        return n;
      case T_WORD_CHAR:
        next();
        return new ReNode(ReNode.WORD_CHAR);
      case T_NON_WORD_CHAR:
        next();
        return new ReNode(ReNode.NON_WORD_CHAR);
      case T_SPACE:
        next();
        return new ReNode(ReNode.SPACE);
      case T_NON_SPACE:
        next();
        return new ReNode(ReNode.NON_SPACE);
      case T_DIGIT:
        next();
        return new ReNode(ReNode.DIGIT);
      case T_NON_DIGIT:
        next();
        return new ReNode(ReNode.NON_DIGIT);
      case T_CLASS:
        n = new ReNode(ReNode.CLASS);
        n.reClass = tokClass;
        next();
        return n;
      default:
        syntaxError();
        return null;
    }
  }
}

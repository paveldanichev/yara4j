package com.paveldan.yara4j;

/**
 * Error codes, mirroring the ERROR_* constants of libyara (include/yara/error.h). The numeric
 * values are the same as in libyara.
 */
public enum ErrorCode {
  SUCCESS(0),
  INSUFFICIENT_MEMORY(1),
  COULD_NOT_ATTACH_TO_PROCESS(2),
  COULD_NOT_OPEN_FILE(3),
  COULD_NOT_MAP_FILE(4),
  INVALID_FILE(6),
  CORRUPT_FILE(7),
  UNSUPPORTED_FILE_VERSION(8),
  INVALID_REGULAR_EXPRESSION(9),
  INVALID_HEX_STRING(10),
  SYNTAX_ERROR(11),
  LOOP_NESTING_LIMIT_EXCEEDED(12),
  DUPLICATED_LOOP_IDENTIFIER(13),
  DUPLICATED_IDENTIFIER(14),
  DUPLICATED_TAG_IDENTIFIER(15),
  DUPLICATED_META_IDENTIFIER(16),
  DUPLICATED_STRING_IDENTIFIER(17),
  UNREFERENCED_STRING(18),
  UNDEFINED_STRING(19),
  UNDEFINED_IDENTIFIER(20),
  MISPLACED_ANONYMOUS_STRING(21),
  INCLUDES_CIRCULAR_REFERENCE(22),
  INCLUDE_DEPTH_EXCEEDED(23),
  WRONG_TYPE(24),
  EXEC_STACK_OVERFLOW(25),
  SCAN_TIMEOUT(26),
  TOO_MANY_SCAN_THREADS(27),
  CALLBACK_ERROR(28),
  INVALID_ARGUMENT(29),
  TOO_MANY_MATCHES(30),
  INTERNAL_FATAL_ERROR(31),
  NESTED_FOR_OF_LOOP(32),
  INVALID_FIELD_NAME(33),
  UNKNOWN_MODULE(34),
  NOT_A_STRUCTURE(35),
  NOT_INDEXABLE(36),
  NOT_A_FUNCTION(37),
  INVALID_FORMAT(38),
  TOO_MANY_ARGUMENTS(39),
  WRONG_ARGUMENTS(40),
  WRONG_RETURN_TYPE(41),
  DUPLICATED_STRUCTURE_MEMBER(42),
  EMPTY_STRING(43),
  DIVISION_BY_ZERO(44),
  REGULAR_EXPRESSION_TOO_LARGE(45),
  TOO_MANY_RE_FIBERS(46),
  COULD_NOT_READ_PROCESS_MEMORY(47),
  INVALID_EXTERNAL_VARIABLE_TYPE(48),
  REGULAR_EXPRESSION_TOO_COMPLEX(49),
  INVALID_MODULE_NAME(50),
  TOO_MANY_STRINGS(51),
  INTEGER_OVERFLOW(52),
  CALLBACK_REQUIRED(53),
  INVALID_OPERAND(54),
  COULD_NOT_READ_FILE(55),
  DUPLICATED_EXTERNAL_VARIABLE(56),
  INVALID_MODULE_DATA(57),
  WRITING_FILE(58),
  INVALID_MODIFIER(59),
  DUPLICATED_MODIFIER(60),
  BLOCK_NOT_READY(61),
  INVALID_PERCENTAGE(62),
  IDENTIFIER_MATCHES_WILDCARD(63),
  INVALID_VALUE(64),
  TOO_SLOW_SCANNING(65),
  UNKNOWN_ESCAPE_SEQUENCE(66);

  private final int code;

  ErrorCode(int code) {
    this.code = code;
  }

  /** Numeric value of this error, identical to libyara's. */
  public int code() {
    return code;
  }

  public static ErrorCode fromCode(int code) {
    for (ErrorCode e : values()) {
      if (e.code == code) {
        return e;
      }
    }
    throw new IllegalArgumentException("unknown error code " + code);
  }
}
